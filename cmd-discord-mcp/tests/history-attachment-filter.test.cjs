"use strict";
const {test}=require("node:test");
const assert=require("node:assert/strict");
const path=require("node:path");
const {pathToFileURL}=require("node:url");
const mod=import(pathToFileURL(path.join(__dirname,"..","cmd-message-history-search.js")).href);
const guild="11111111-1111-4111-8111-111111111111",channel="22222222-2222-4222-8222-222222222222";
const dm="33333333-3333-4333-8333-333333333333";
const url=(params)=>new URL("https://cmd.test/api/cmd/messages/history-search?"+new URLSearchParams({scope:"server",guildId:guild,channelId:channel,q:"photo",...params}));
test("optional file filter is strictly parsed and limited to server channels",async()=>{
 const {cmdHistoryParameters:p}=await mod;
 assert.equal(p(url({})).hasFile,null);
 assert.equal(p(url({hasFile:"true"})).hasFile,true);
 assert.equal(p(url({hasFile:"false"})).hasFile,false);
 for(const value of ["1","TRUE","no","true;DROP TABLE messages"])assert.throws(()=>p(url({hasFile:value})),e=>e.status===400);
 assert.throws(()=>p(url({scope:"dm",threadId:dm,hasFile:"true"})),e=>e.status===400);
 assert.throws(()=>p(url({scope:"group",groupId:dm,hasFile:"false"})),e=>e.status===400);
});
test("authorized native attachment filter uses positional SQL and keeps channel membership checks",async()=>{
 const {cmdHistoryParameters:p,searchCmdHistory:search}=await mod;
 const requests=[];
 const pool={async query(sql,params){requests.push({sql,params});
  if(sql.includes("SELECT membership_role"))return {rows:[{membership_role:"member"}]};
  if(sql.includes("SELECT c.id::text"))return {rows:[{id:channel,type:"text",name:"photos",permission_overwrites:[],parent_overwrites:[]}]};
  if(sql.includes("SELECT m.id::text"))return {rows:[{id:"m1",content:"photo autorisée"}]};
  throw Error("Unexpected SQL");
 }};
 const permissions=async()=>({viewChannels:true,readHistory:true});
 const result=await search(pool,{user:{id:"member1"}},p(url({hasFile:"true"})),{checkGuildPermissions:permissions});
 assert.equal(result.results.length,1);
 assert.equal(result.hasFile,true);
 assert.equal(requests.length,3);
 assert.match(requests[2].sql,/jsonb_array_length\(m\.attachments\)/);
 assert.match(requests[2].sql,/m\.guild_id=\$8::uuid AND m\.channel_id=\$3::uuid/);
 assert.equal(requests[2].params[7],guild);
 assert.equal(requests[2].params[8],true);
});
test("ordinary members cannot evade permissions with an attachment filter",async()=>{
 const {cmdHistoryParameters:p,searchCmdHistory:search}=await mod;
 let calls=0;
 const pool={async query(sql){calls++;
  if(sql.includes("SELECT membership_role"))return {rows:[]};
  throw Error("Message SQL must not execute for an outsider");
 }};
 await assert.rejects(search(pool,{user:{id:"outsider"}},p(url({hasFile:"true"}))),e=>e.status===403);
 assert.equal(calls,1);
});
test("disabled file filter leaves existing message data untouched",async()=>{
 const {cmdHistoryParameters:p,searchCmdHistory:search}=await mod;
 const calls=[];
 const pool={async query(sql,args){calls.push([sql,args]);
  if(sql.includes("SELECT membership_role"))return {rows:[{membership_role:"owner"}]};
  if(sql.includes("SELECT c.id::text"))return {rows:[{id:channel,type:"text",name:"photos",permission_overwrites:[],parent_overwrites:[]}]};
  return {rows:[{id:"1",content:"ancienne photo"}]};
 }};
 const result=await search(pool,{user:{id:"owner"}},p(url({})));
 assert.equal(result.hasFile,null);
 assert.equal(calls[2][1][8],null);
 assert.equal(result.results[0].content,"ancienne photo");
 assert.match(calls[2][0],/SELECT m\.id/);
 assert.doesNotMatch(calls[2][0],/DELETE|UPDATE|TRUNCATE/i);
});
